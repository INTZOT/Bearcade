/**
 * 剥离 § 格式化控制码(§a-§f、§0-§9、§k-§r 等),用于玩家名等不可信文本拼入
 * 公告/名牌/聊天/浮空字之前,防止格式码注入(伪造他人发言样式、刷色)。
 */
export function stripSectionCodes(text: string): string {
  return text.replace(/§./g, "");
}
